import type { AnalysisResult, Finding, Severity } from './types';

const TOOL_NAME = 'LocalAudit';
const TOOL_VERSION = '0.2.0';
const SEVERITY_ORDER: Severity[] = ['critical', 'medium', 'low'];
const SARIF_LEVEL: Record<Severity, 'error' | 'warning' | 'note'> = {
  critical: 'error',
  medium: 'warning',
  low: 'note',
};
/** GitHub code scanning maps `security-severity` (0-10) to its own severity labels. */
const SECURITY_SEVERITY: Record<Severity, string> = { critical: '9.0', medium: '5.5', low: '2.0' };

function ruleIdOf(finding: Finding): string {
  return finding.ruleId ?? finding.id;
}

function sortBySeverity(findings: Finding[]): Finding[] {
  return [...findings].sort((a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity));
}

export function toJsonReport(result: AnalysisResult, generatedAt = new Date()): string {
  return JSON.stringify(
    {
      tool: { name: TOOL_NAME, version: TOOL_VERSION },
      generatedAt: generatedAt.toISOString(),
      score: result.score,
      counts: result.counts,
      findings: sortBySeverity(result.findings).map(({ id: _id, ...finding }) => finding),
    },
    null,
    2,
  );
}

export function toMarkdownReport(result: AnalysisResult, generatedAt = new Date()): string {
  const { critical, medium, low } = result.counts;
  const lines = [
    '# Security audit report',
    '',
    `Generated by ${TOOL_NAME} on ${generatedAt.toISOString()}.`,
    '',
    `**Score:** ${result.score}/100 · **Critical:** ${critical} · **Medium:** ${medium} · **Low:** ${low}`,
    '',
  ];

  if (result.findings.length === 0) {
    lines.push('No findings.');
    return lines.join('\n');
  }

  const sorted = sortBySeverity(result.findings);
  lines.push('| Severity | File | Line | Finding | References |', '| --- | --- | --- | --- | --- |');
  for (const finding of sorted) {
    lines.push(
      `| ${finding.severity} | \`${finding.sourceFile}\` | ${finding.line ?? '—'} | ${finding.title.replace(/\|/g, '\\|')} | ${(finding.references ?? []).join(', ')} |`,
    );
  }

  lines.push('', '## Details', '');
  for (const finding of sorted) {
    const location = finding.line ? `${finding.sourceFile}:${finding.line}` : finding.sourceFile;
    lines.push(
      `### [${finding.severity.toUpperCase()}] ${finding.title}`,
      '',
      `- **Location:** \`${location}\``,
      `- **Category:** ${finding.category}`,
      `- **Rule:** \`${ruleIdOf(finding)}\``,
      '',
      finding.description,
      '',
      '```',
      finding.fixSnippet,
      '```',
      '',
    );
  }

  return lines.join('\n');
}

/** SARIF 2.1.0, accepted by GitHub code scanning, GitLab and most security dashboards. */
export function toSarifReport(result: AnalysisResult): string {
  const rules = new Map<string, Finding>();
  for (const finding of result.findings) {
    if (!rules.has(ruleIdOf(finding))) rules.set(ruleIdOf(finding), finding);
  }

  const sarif = {
    $schema: 'https://json.schemastore.org/sarif-2.1.0.json',
    version: '2.1.0',
    runs: [
      {
        tool: {
          driver: {
            name: TOOL_NAME,
            version: TOOL_VERSION,
            rules: [...rules.entries()].map(([id, finding]) => ({
              id,
              name: finding.category.replace(/[^A-Za-z0-9]/g, ''),
              shortDescription: { text: finding.title },
              fullDescription: { text: finding.description },
              help: { text: finding.fixSnippet },
              properties: {
                tags: ['security', ...(finding.references ?? [])],
                'security-severity': SECURITY_SEVERITY[finding.severity],
              },
            })),
          },
        },
        results: result.findings.map((finding) => ({
          ruleId: ruleIdOf(finding),
          level: SARIF_LEVEL[finding.severity],
          message: { text: `${finding.title}. ${finding.description}` },
          locations: [
            {
              physicalLocation: {
                artifactLocation: { uri: finding.sourceFile },
                region: { startLine: finding.line ?? 1 },
              },
            },
          ],
        })),
      },
    ],
  };

  return JSON.stringify(sarif, null, 2);
}

export function downloadTextFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}
